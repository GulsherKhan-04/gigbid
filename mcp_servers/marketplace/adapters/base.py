from __future__ import annotations

from typing import Any, Protocol


class MarketBackend(Protocol):
    async def search_jobs(self, query: str, limit: int) -> list[dict[str, Any]]: ...
    async def get_job(self, job_id: str) -> dict[str, Any]: ...
    async def get_client_history(self, client_id: str) -> dict[str, Any]: ...
    async def get_connects_balance(self, user: str) -> dict[str, Any]: ...
    async def list_messages(self, user: str, thread_id: str | None) -> list[dict[str, Any]]: ...
    async def create_proposal_draft(self, user: str, payload: dict[str, Any]) -> dict[str, Any]: ...
    async def submit_proposal(self, user: str, draft_id: str) -> dict[str, Any]: ...
    async def send_message(self, user: str, thread_id: str, text: str) -> dict[str, Any]: ...


class BackendUnavailable(RuntimeError):
    pass
